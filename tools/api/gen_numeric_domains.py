"""Project selected C numeric domains into the private WASM domain module."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tools/api/numeric-domains.json"
TARGET = ROOT / "bindings/wasm/src/internal/numeric_domains.ts"
PROJECTIONS = (
    ("resample", "target_sample_rate", "AUDIO_SAMPLE_RATE_DOMAIN"),
    ("engine_configure_scope_telemetry", "interval_frames", "SCOPE_INTERVAL_DOMAIN"),
    ("engine_configure_scope_telemetry", "band_count", "SCOPE_BAND_DOMAIN"),
)


def projected_rows() -> list[tuple[str, int, int]]:
    rows = json.loads(SOURCE.read_text())["rows"]
    output: list[tuple[str, int, int]] = []
    for entry, param, name in PROJECTIONS:
        matching = [row for row in rows if row["entry"] == entry and row["param"] == param]
        if len(matching) != 1:
            raise SystemExit(f"{entry}.{param} must have one numeric domain")
        row = matching[0]
        lo, hi = row["lo"], row["hi"]
        if (
            row["kind"] != "integer"
            or type(lo) is not int
            or type(hi) is not int
            or row["lo_included"] is not True
            or row["hi_included"] is not True
        ):
            raise SystemExit(f"{entry}.{param} must have a closed integer domain")
        output.append((name, lo, hi))
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = "// Generated by tools/api/gen_numeric_domains.py; do not edit.\n"
    for name, lo, hi in projected_rows():
        output += f"export const {name} = [{lo}, {hi}] as const;\n"

    if args.check:
        if not TARGET.exists() or TARGET.read_text() != output:
            raise SystemExit(f"{TARGET.relative_to(ROOT)} is stale; run make numeric-domains")
    else:
        TARGET.write_text(output)


if __name__ == "__main__":
    main()
