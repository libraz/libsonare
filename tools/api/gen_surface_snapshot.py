"""Render the public declarations and source-level defaults used by each surface."""

from __future__ import annotations

import argparse
import concurrent.futures
import difflib
import json
import subprocess
import sys
from pathlib import Path

import inventory

SURFACES = ("c", "node", "wasm", "python", "cli")
HEADER = "# Generated by make surface-snapshot.\n"


def type_rows(entry, row, name):
    """Project a TypeScript export or member, keeping overload and field shape."""
    prefix = f"{entry} {name}"
    kind = row["kind"]
    detail = ""
    if kind in ("property", "accessor", "method"):
        detail = " optional" if row["optional"] else " required"
        if row["readonly"]:
            detail += " readonly"
    if row.get("type") and kind != "method":
        detail += f" : {row['type']}"
    yield f"{prefix} {kind}{detail}"
    if not row.get("ctorPrivate"):
        for i, sig in enumerate(row["sigs"], 1):
            defaults = ", ".join(
                f"{p['name']} = {p['default']}" for p in sig["params"] if "default" in p
            )
            suffix = f" defaults ({defaults})" if defaults else ""
            yield f"{prefix} signature {i:02d} {sig['text']}{suffix}"
    for member in row.get("members", []) + row.get("nested", []):
        separator = " static " if member["static"] else "."
        yield from type_rows(entry, member, f"{name}{separator}{member['name']}")
    for member in row.get("enumMembers", []):
        yield f"{prefix}.{member['name']} value"


def typescript_rows(root, pkg, entries):
    raw = subprocess.check_output(
        [
            "node",
            str(root / "tools/api/ts_exports.cjs"),
            str(root / "bindings" / pkg),
            "--snapshot",
            *sorted(set(entries.values())),
        ],
        text=True,
    )
    data = json.loads(raw)
    if not data["exports"]:
        return
    for label, entry in entries.items():
        for row in data["exports"]:
            if row["entry"] == entry:
                yield from type_rows(label, row, row["name"])
    for row in data["defaults"]:
        yield f"default {row['file']}:{row['scope']} {row['field']} = {row['value']}"
    package = json.loads((root / "bindings" / pkg / "package.json").read_text(encoding="utf-8"))
    for entry in package.get("exports", {}):
        yield f"entry {entry}"


def declaration_rows(records, surface):
    dataclasses = {row["name"] for row in records if row.get("dataclass")}
    for row in records:
        kind, name = row["kind"], row["name"]
        if kind == "option":
            continue  # The parameter is already present on the declaration.
        modules = " ".join(row.get("modules", []))
        prefix = f"{modules} {name}" if modules else name
        detail = ""
        if kind == "field":
            omittable = row.get("field_omittable", row.get("optional", False))
            detail = " optional" if omittable else " required"
        elif row.get("dataclass"):
            detail = f" {' '.join(row['decorators'])}"
        elif row.get("frozen"):
            detail = " frozen"
        if row.get("bases"):
            detail += f" bases ({', '.join(row['bases'])})"
        if row.get("type"):
            detail += f" : {row['type']}"
        if row.get("field_default"):
            detail += f" = {row['field_default']}"
        if (surface == "c" and kind in ("field", "value")) or (
            kind == "field" and row["owner"] in dataclasses
        ):
            index = row["index"] + (kind == "field")
            detail += f" (member {index})"

        decls = list(row.get("declarations", []))
        if not decls:
            for sig in row.get("sigs", []):
                parameters = ", ".join(f"{p['type']} {p['name']}".strip() for p in sig["params"])
                decls.append(f"({parameters}) -> {sig['returns']}")
        if decls:
            for i, decl in enumerate(decls, 1):
                order = f" signature {i:02d}" if len(decls) > 1 else ""
                yield f"{prefix} {kind}{detail}{order} {decl}"
        else:
            yield f"{prefix} {kind}{detail}"


def cli_rows(root):
    records, _, meta = inventory.extract_cli(root, snapshot=True)
    for row in records:
        kind = row["kind"]
        suffix = ""
        if row.get("spec"):
            suffix = f" {row['spec']}"
        elif kind == "flag":
            suffix = " switch" if row.get("boolean") else " value"
        if row.get("alias_of"):
            suffix += f" alias of --{row['alias_of']}"
        yield f"{row['surface']} {row['name']} {kind}{suffix}"
    for file, scope, flag, default in meta["cli_python_defaults"]:
        yield f"cli-python default {file}:{scope} --{flag} = {default}"


def snapshot_rows(root):
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        node = pool.submit(list, typescript_rows(root, "node", {".": "index.ts"}))
        wasm = pool.submit(list, typescript_rows(root, "wasm", inventory.wasm_entries(root)))
        c = list(declaration_rows(inventory.extract_c(root, snapshot=True)[0], "c"))
        python = list(declaration_rows(inventory.extract_python(root)[0], "python"))
        cli = list(cli_rows(root))
        return dict(zip(SURFACES, (c, node.result(), wasm.result(), python, cli), strict=True))


def write_or_check(root, surfaces, *, check):
    """Check all surfaces before writing, and always show the actual changed rows."""
    rendered = {}
    for surface in SURFACES:
        # A multiline declaration stays one item, without embedding path or line metadata.
        items = sorted({row.replace("\r", "\\r").replace("\n", "\\n") for row in surfaces[surface]})
        print(f"{surface}: {len(items)} snapshot items")
        if not items:
            print(f"{surface}: no public surface items extracted", file=sys.stderr)
        rendered[surface] = items
    if not all(rendered.values()):
        return 1

    drift = False
    for surface, items in rendered.items():
        relative = Path("tools/api") / f"surface-snapshot-{surface}.txt"
        path = root / relative
        expected = HEADER + "\n".join(items) + "\n"
        if not check:
            path.write_text(expected, encoding="utf-8", newline="\n")
            continue
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual != expected:
            drift = True
            diff = difflib.unified_diff(
                actual.splitlines(keepends=True),
                expected.splitlines(keepends=True),
                fromfile=str(relative),
                tofile=f"{relative} (regenerated)",
            )
            sys.stdout.writelines(diff)
    if drift:
        print("Public surface snapshot drift. Run make surface-snapshot and review the diff.")
    return int(drift)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Show drift without writing files.")
    args = parser.parse_args()
    return write_or_check(inventory.ROOT, snapshot_rows(inventory.ROOT), check=args.check)


if __name__ == "__main__":
    sys.exit(main())
