"""Generate the C entry name table the Node addon and the WASM module strip with.

A C entry names itself on a refusal ("project_add_clip: clip_id ..."); the
public entry the consumer called prefixes its own name on the way out, so each
binding drops a leading "<token>: " when sonare_<token> is a C entry. The list
comes from the public headers through the parity C extractor, and the same
header is written into both binding trees.

Usage: python3 tools/parity/gen_c_entry_names.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from extractors import c_api

ROOT = Path(__file__).resolve().parents[2]
TARGETS = (
    ROOT / "bindings/node/src/addon/c_entry_names.h",
    ROOT / "src/wasm/c_entry_names.h",
)
PREFIX = "sonare_"


def render(tokens: list[str]) -> str:
    rows = "\n".join(f'    "{t}",' for t in tokens)
    return f"""// Generated by tools/parity/gen_c_entry_names.py from include/sonare; do not edit.
#pragma once

#include <algorithm>
#include <cstddef>
#include <iterator>
#include <string_view>

namespace sonare_c_entries {{

// Every public C entry name without its sonare_ prefix, sorted.
inline constexpr std::string_view kTokens[] = {{
{rows}
}};

// True when sonare_<token> is a public C entry.
inline bool IsCEntryToken(std::string_view token) {{
  return std::binary_search(std::begin(kTokens), std::end(kTokens), token);
}}

inline bool IsTokenChar(char c) {{
  return (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_';
}}

// Length of a leading "<token>: " the C layer put on its text when sonare_<token>
// is a C entry, else 0; the public entry names itself instead. Other prefixes stay.
inline std::size_t CEntryPrefixLength(std::string_view message) {{
  if (message.empty() || message[0] < 'a' || message[0] > 'z') return 0;
  std::size_t i = 0;
  while (i < message.size() && IsTokenChar(message[i])) ++i;
  if (i + 1 >= message.size() || message[i] != ':' || message[i + 1] != ' ') return 0;
  std::string_view token = message.substr(0, i);
  if (token.substr(0, {len(PREFIX)}) == "{PREFIX}") token.remove_prefix({len(PREFIX)});
  return IsCEntryToken(token) ? i + 2 : 0;
}}

}}  // namespace sonare_c_entries
"""


def main(argv: list[str]) -> int:
    ex = c_api.extract(ROOT)
    if ex.unparsed:
        print(
            f"c entries: {ex.unparsed} declarations unparsed: {ex.unparsed_notes}", file=sys.stderr
        )
        return 1
    names = sorted({f.raw_name for f in ex.functions})
    tokens = sorted(n[len(PREFIX) :] for n in names if n.startswith(PREFIX))
    if not tokens:
        print("c entries: none found", file=sys.stderr)
        return 1
    text = render(tokens)
    check = "--check" in argv
    stale = []
    for target in TARGETS:
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        if check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8")
    print(f"c entries: {len(tokens)} tokens, {len(TARGETS)} tables")
    if stale:
        print(
            f"c entries: stale {', '.join(stale)}; run tools/parity/gen_c_entry_names.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
