/* The bank: every GM program and GS variation the library voices, whatever has
 * been rendered. The listening surface shows one voice; this shows where all of
 * them stand, which is the half of the work that is otherwise only visible to
 * whoever remembers what has been captured.
 *
 * Three bands, because one list of 188 rows answers only the question you were
 * already on. The masthead is the overview — totals and the distribution across
 * the six stages — the toolbar narrows, and the table lists beside an inspector
 * that holds what a row cannot: the coverage denominator, which dimensions sit
 * outside the reference spread and by how much, and the ladder in full.
 *
 * It reads `tools/voice-status.json`, which is committed and generated by
 * `tools/voicematch/status.py`. Opening a voice is handed back to the caller
 * rather than reached for here: this file is the bank and knows nothing about
 * the transport.
 */

