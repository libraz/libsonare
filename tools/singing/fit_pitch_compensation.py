"""Regenerate or check the singing voice's pitch compensation table.

The fold's F0 rises with lung pressure, so the tension a note asks for depends on
the breath. The table holds, per (force, pitch) grid point, the fold tension that
sounds the pitch at that force. It is a property of the valve model rather than of
any patch: change the model and the table is stale.

The measurement is not done here. `sonare_singing_sweep` (tools/singing/) fits
every cell on the SingingPhonation the engine renders, through the same code the
drift test (tests/midi/singing_pitch_compensation_test.cpp) runs at the four
corners. This script owns the grid, runs the sweep once, and writes the table.

    rye run --pyproject bindings/python/pyproject.toml python tools/singing/fit_pitch_compensation.py
    rye run --pyproject bindings/python/pyproject.toml python tools/singing/fit_pitch_compensation.py --check

The sweep is deterministic, so a second run writes the same bytes.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from _repo import REPO_ROOT

OUTPUT_PATH = REPO_ROOT / "src/midi/synth/singing_pitch_compensation.inc"
SWEEP_PATH = REPO_ROOT / "build/bin/sonare_singing_sweep"

#: Breath axis grid. Dense at the low end, where F0 is most sensitive to the
#: breath, starting where every pitch of the grid phonates periodically: up to 0.34
#: the reference tract holds A2 in an irregular subharmonic regime with no stable F0.
FORCES = (0.39, 0.45, 0.52, 0.6, 0.7, 0.83, 1.0)

#: Pitch grid: every other semitone from A2 to C#4, the range the reference tract
#: compensates without its F0 locking onto a formant. On equal-tempered notes so
#: half the keys read the table without interpolating across pitch.
PITCH_LOW_NOTE = 45
PITCH_STEP_SEMITONES = 2
PITCH_COUNT = 9


def pitches() -> list[float]:
    """The pitch grid in Hz, as float32 literals of the equal-tempered notes."""
    return [
        float(f"{440.0 * 2.0 ** ((PITCH_LOW_NOTE + PITCH_STEP_SEMITONES * k - 69) / 12.0):.6g}")
        for k in range(PITCH_COUNT)
    ]


def sweep(binary: Path, grid_pitches: list[float]) -> list[list[float]]:
    """One row of fitted tensions per force, from the sweep tool."""
    if not binary.exists():
        raise SystemExit(f"{binary}: not built (target sonare_singing_sweep)")
    args = [str(binary), "--force", *(repr(f) for f in FORCES), "--pitch"]
    args += [repr(p) for p in grid_pitches]
    result = subprocess.run(args, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"sweep failed:\n{result.stderr}")
    rows = [[float(x) for x in line.split()] for line in result.stdout.splitlines() if line]
    if len(rows) != len(FORCES) or any(len(r) != len(grid_pitches) for r in rows):
        raise SystemExit(f"sweep returned a {len(rows)}-row table, expected {len(FORCES)}")
    return rows


def literal(value: float) -> str:
    """A C float literal that round-trips the sweep's printed value."""
    text = f"{value:.9g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def render(grid_pitches: list[float], rows: list[list[float]]) -> str:
    def array(values: list[float] | tuple[float, ...]) -> str:
        return ", ".join(literal(v) for v in values)

    body = ",\n".join(f"    {{{array(row)}}}" for row in rows)
    return (
        "// Generated by tools/singing/fit_pitch_compensation.py; do not edit by hand.\n"
        "// Fold tension over the note's own that sounds each pitch at each force,\n"
        "// fitted on SingingPhonation at the SingingPatchParams defaults, 48000 Hz.\n"
        "// clang-format off\n"
        "\n"
        f"inline constexpr int kSingingCompForceCount = {len(FORCES)};\n"
        f"inline constexpr int kSingingCompPitchCount = {len(grid_pitches)};\n"
        "inline constexpr float kSingingCompForce[kSingingCompForceCount] = {\n"
        f"    {array(FORCES)}}};\n"
        "inline constexpr float kSingingCompPitchHz[kSingingCompPitchCount] = {\n"
        f"    {array(grid_pitches)}}};\n"
        "inline constexpr float kSingingCompTension[kSingingCompForceCount]"
        "[kSingingCompPitchCount] = {\n"
        f"{body}}};\n"
        "// clang-format on\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sweep", type=Path, default=SWEEP_PATH, help="sweep tool binary")
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH, help="table to write")
    parser.add_argument(
        "--check", action="store_true", help="fail instead of writing when the table differs"
    )
    args = parser.parse_args()

    grid_pitches = pitches()
    text = render(grid_pitches, sweep(args.sweep, grid_pitches))
    current = args.output.read_text() if args.output.exists() else None
    if args.check:
        if current != text:
            print(f"{args.output}: stale; regenerate with {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{args.output}: current")
        return 0
    args.output.write_text(text)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
