#!/usr/bin/env python3
"""Generate schemas/result-null-means.json from the core's per-result null lists.

A JSON result writes a NaN member as an absent key and an infinite one as null, so
a null alone does not say which infinity it stands for. Each result family that can
write one states it beside its path list, as a literal
`<family>_null_means()` list of {path, end} pairs, and a C++ conformance case holds
every writer to its list. This script copies those lists into a JSON file, a
Python module and a TypeScript module per JS binding, so no surface hand-copies
an end.

The families are the result schema surface check's own table. Each list is read
textually and must be a literal initializer: one that computes an entry is refused
rather than read partially. A listed path must be one the family's path list names
(an array element is spelled `<array>[]`), and an end is `-Infinity` or `Infinity`.
A family whose list is empty is published with no paths, so a reader names it and a
null in its result is refused; a family with no list at all is not published.
A `*_null_means()` definition outside the table is refused too, since nothing would
publish it. `--check` exits 1 when the file is not what this script would write.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests/conformance"))

import check_result_schema_surfaces as surfaces
import ts_surface_walk as walk

OUTPUT = ROOT / "schemas/result-null-means.json"
PY_OUTPUT = ROOT / "bindings/python/src/libsonare/_null_means.py"
TS_OUTPUTS = (
    ROOT / "bindings/node/src/internal/result_null_means.ts",
    ROOT / "bindings/wasm/src/internal/result_null_means.ts",
)
ENDS = ("-Infinity", "Infinity")
_DECLARATION = (
    r"_null_means\(\)\s*\{\s*static const std::vector<std::pair<std::string, std::string>>"
    r"\s+means\s*=\s*\{"
)
_PAIR = re.compile(r'\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\}')
_DEFINITION = re.compile(r"&\s*(\w+)_null_means\(\)\s*\{")


def null_means(source: str, family: str) -> list[tuple[str, str]] | None:
    """The pairs `<family>_null_means()` lists, None when unreadable or not defined."""
    match = re.search(r"\b" + re.escape(family) + _DECLARATION, source)
    if match is None:
        return None
    body = walk.brace_body(source, match.end() - 1)
    if body is None:
        return None
    inner = re.sub(r"//[^\n]*", "", body[1:-1])
    if re.sub(r"[\s,]", "", _PAIR.sub("", inner)):
        return None
    return _PAIR.findall(inner)


def collect() -> tuple[dict, list[str]]:
    families: dict[str, dict] = {}
    problems: list[str] = []
    known: set[str] = set()
    for label, entry in surfaces.FAMILIES.items():
        family = label.removesuffix("_schema_paths")
        known.add(family)
        source = entry["source"].read_text(encoding="utf-8")
        if not re.search(r"\b" + re.escape(family) + r"_null_means\(\)", source):
            continue
        pairs = null_means(source, family)
        if pairs is None:
            problems.append(f"{family}_null_means() is not a literal list of pairs")
            continue
        listed = set(surfaces.schema_paths(source, label) or [])
        means: dict[str, str] = {}
        for path, end in pairs:
            if end not in ENDS:
                problems.append(f"{family}: {path} names {end!r}, not one of {', '.join(ENDS)}")
            if path.removesuffix("[]") not in listed:
                problems.append(f"{family}: {path} is not in {label}()")
            if path in means:
                problems.append(f"{family}: {path} is listed twice")
            means[path] = end
        families[family] = {"root": entry["root"], "nullMeans": dict(sorted(means.items()))}
    for path in sorted((ROOT / "src").rglob("*.cpp")):
        for name in _DEFINITION.findall(path.read_text(encoding="utf-8")):
            if name not in known:
                problems.append(
                    f"{path.relative_to(ROOT)}: {name}_null_means() has no result family to publish it"
                )
    return families, problems


def render(families: dict) -> str:
    document = {
        "$comment": (
            "Generated by tools/conformance/gen_null_means.py from each result family's "
            "<family>_null_means() list; run make result-null-means after changing one. "
            "A null at a listed path stands for the named infinite end."
        ),
        "families": dict(sorted(families.items())),
    }
    return json.dumps(document, indent=2) + "\n"


def render_python(families: dict) -> str:
    """The same table as a Python module, each end as the float it stands for."""
    lines = [
        '"""Generated by tools/conformance/gen_null_means.py; do not edit."""',
        "",
        "import math",
        "",
        "# Result family -> dotted path (`[]` per array segment, `<array>[]` for an element)",
        "# -> the infinite end a JSON null at that path stands for.",
        "NULL_MEANS: dict[str, dict[str, float]] = {",
    ]
    for family, entry in sorted(families.items()):
        if not entry["nullMeans"]:
            lines.append(f'    "{family}": {{}},')
            continue
        lines.append(f'    "{family}": {{')
        for path, end in entry["nullMeans"].items():
            value = "math.inf" if end == "Infinity" else "-math.inf"
            lines.append(f'        "{path}": {value},')
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_typescript(families: dict) -> str:
    """The same table as a TypeScript module, in the bindings' Biome style."""
    lines = [
        "// Generated by tools/conformance/gen_null_means.py; do not edit.",
        "",
        "/**",
        " * Result family -> dotted path (`[]` per array segment, `<array>[]` for an",
        " * element) -> the infinite end a JSON null at that path stands for.",
        " */",
        "export const NULL_MEANS: Readonly<Record<string, Readonly<Record<string, number>>>> = {",
    ]
    for family, entry in sorted(families.items()):
        if not entry["nullMeans"]:
            lines.append(f"  {family}: {{}},")
            continue
        lines.append(f"  {family}: {{")
        for path, end in entry["nullMeans"].items():
            value = "Number.POSITIVE_INFINITY" if end == "Infinity" else "Number.NEGATIVE_INFINITY"
            key = path if re.fullmatch(r"[A-Za-z_$][\w$]*", path) else f"'{path}'"
            lines.append(f"    {key}: {value},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args()
    families, problems = collect()
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1
    if not families:
        print("no result family declares a null end; the lists were not found", file=sys.stderr)
        return 1
    outputs = {OUTPUT: render(families), PY_OUTPUT: render_python(families)}
    outputs.update(dict.fromkeys(TS_OUTPUTS, render_typescript(families)))
    count = sum(len(family["nullMeans"]) for family in families.values())
    if args.check:
        stale = [
            path
            for path, wanted in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != wanted
        ]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale: run make result-null-means", file=sys.stderr)
        if stale:
            return 1
        print(f"result null means: up to date ({len(families)} families, {count} paths)")
        return 0
    for path, wanted in outputs.items():
        staged = path.with_name(path.name + ".tmp")
        staged.write_text(wanted, encoding="utf-8")
        os.replace(staged, path)
    print(f"result null means: wrote {len(families)} families, {count} paths")
    return 0


if __name__ == "__main__":
    sys.exit(main())
