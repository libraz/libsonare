"""Which objective each patch was last fitted under, so a stale fit is visible.

`fits.json` holds one record per calibration unit — a named patch, a `famN`
family or a `dNNN` drum note, the same keys `bank-versions.json` uses — saying
which objective fingerprint (`objective.py`) the last completed fit answered,
against which capture and timbre, and whether its values were adopted or the
shipped values kept. A kept outcome is a fit too: it says the current objective
was asked and the shipped values stood.

The record is written by `record` from a fit's `--out` report, after the
adoption decision rather than by `autofit.py` itself, because whether a fit is
adopted is decided by comparing gates, which happens after the fit. `status.py`
reads it into each voice's `fit` axis.

    fits.py record --report fit.json --capture <id> --timbre <t> --outcome adopted
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

import objective

HERE = Path(__file__).resolve().parent
FITS_PATH = HERE / "fits.json"

OUTCOMES = ("adopted", "kept")
CURRENT, STALE, NONE = "current", "stale", "none"

DOC = (
    "Generated by tools/voicematch/fits.py record. One entry per calibration unit: the "
    "objective fingerprint (objective.py) its last completed fit answered, the capture and "
    "timbre it was fitted against, and whether the values were adopted or the shipped ones "
    "kept. status.py reads it into each voice's fit axis."
)


def load(path: Path = FITS_PATH) -> dict[str, dict]:
    if not path.exists():
        return {}
    return json.loads(path.read_text()).get("fits", {})


def save(fits: dict[str, dict], path: Path = FITS_PATH) -> None:
    body = {"_doc": DOC, "fits": {k: fits[k] for k in sorted(fits)}}
    path.write_text(json.dumps(body, indent=2) + "\n")


def unit_of(report: dict) -> str:
    """The one unit a `--program-only` report's knobs belong to."""
    units = {k["key"].partition(".")[0] for k in report.get("knobs", [])}
    if len(units) != 1:
        raise ValueError(
            f"a fit record needs knobs from exactly one patch, got {sorted(units)}; "
            f"fit with --program-only"
        )
    return units.pop()


def record_fit(
    report: dict,
    *,
    capture: str,
    timbre: str,
    outcome: str,
    reason: str = "",
    bank_generation: int = 0,
    today: str | None = None,
) -> tuple[str, dict]:
    if outcome not in OUTCOMES:
        raise ValueError(f"outcome is one of {', '.join(OUTCOMES)}, not {outcome!r}")
    digest = report.get("objective")
    if not digest:
        raise ValueError("the report carries no objective fingerprint; re-run the fit")
    entry = {
        "objective": digest,
        "date": today or datetime.datetime.now(tz=datetime.timezone.utc).date().isoformat(),
        "capture": capture,
        "timbre": timbre,
        "outcome": outcome,
    }
    if reason:
        entry["reason"] = reason
    if bank_generation:
        entry["bank_generation"] = bank_generation
    return unit_of(report), entry


def axis(units: list[str], fits: dict[str, dict], digest: str) -> dict:
    """A voice's fit state over its units: the worst of them, `none` if any has no record."""
    if not units:
        return {"state": NONE}
    entries = [fits.get(u) for u in units]
    if any(e is None for e in entries):
        state = NONE
    elif any(e["objective"] != digest for e in entries):
        state = STALE
    else:
        state = CURRENT
    out: dict = {"state": state}
    recorded = [e for e in entries if e is not None]
    if recorded:
        last = max(recorded, key=lambda e: e["date"])
        out.update(date=last["date"], outcome=last["outcome"])
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    rec = sub.add_parser("record", help="record a completed fit from its --out report")
    rec.add_argument("--report", required=True)
    rec.add_argument("--capture", required=True)
    rec.add_argument("--timbre", required=True)
    rec.add_argument("--outcome", required=True, choices=OUTCOMES)
    rec.add_argument("--reason", default="")
    rec.add_argument("--bank-generation", type=int, default=0)
    sub.add_parser("digest", help="print the current objective fingerprint")
    args = ap.parse_args()
    if args.cmd == "digest":
        print(objective.objective_digest())
        return 0
    report = json.loads(Path(args.report).read_text())
    unit, entry = record_fit(
        report,
        capture=args.capture,
        timbre=args.timbre,
        outcome=args.outcome,
        reason=args.reason,
        bank_generation=args.bank_generation,
    )
    fits = load()
    fits[unit] = entry
    save(fits)
    print(f"{unit}: {entry['outcome']} under objective {entry['objective']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
