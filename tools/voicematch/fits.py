"""Which objective each patch was last fitted under, so a stale fit is visible.

`fits.json` holds one record per calibration unit — a named patch, a `famN`
family or a `dNNN` drum note, the same keys `bank-versions.json` uses — saying
which objective fingerprint (`objective.py`) the last completed fit answered,
against which capture and timbre, and whether its values were adopted or the
shipped values kept. A kept outcome is a fit too: it says the current objective
was asked and the shipped values stood. A blocked outcome is a refit whose trade
`refit.py resolve` could not settle: the shipped values stand because every point
of the search broke a gated row, and the entry names those rows in `blocking`.

The record is written by `record` from a fit's `--out` report, after the
adoption decision rather than by `autofit.py` itself, because whether a fit is
adopted is decided by comparing gates, which happens after the fit. `status.py`
reads it into each voice's `fit` axis.

    fits.py record --report fit.json --capture <id> --timbre <t> --outcome adopted

An entry carries `corpora`, the `{capture, timbre}` list the fit answered (a joint
fit names several; one capture is a list of one), beside `capture` and `timbre`,
which stay the first of them.
"""

from __future__ import annotations

import argparse
import datetime
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # tools/, for knobs' _repo

import equivalence
import objective
from knobs import parse_overrides

HERE = Path(__file__).resolve().parent
FITS_PATH = HERE / "fits.json"
BANK_VERSIONS_PATH = HERE.parents[1] / "tools" / "bank-versions.json"

OUTCOMES = ("adopted", "kept", "blocked")
#: Only `refit.py adopt` writes `blocked`, since it carries the rows read from the refit's files.
BY_HAND = ("adopted", "kept")
CURRENT, EQUIVALENT, STALE, NONE = "current", "equivalent", "stale", "none"
#: A refit under this objective whose best point trades gated rows: mechanism work, not a refit.
BLOCKED = "blocked"
#: Fitted on top of engine constants not yet committed: never `current` until they are.
UNDER_BASE = "under_base"
#: Fitted against a capture off the layer the slot is aimed at, because no capture on it exists.
OFF_LAYER = "provisional_off_layer"
#: Scored with a term its class weighs switched off (an oracle read from a cache): never `current`.
SCORED_WITHOUT = "scored_without"

DOC = (
    "Generated by tools/voicematch/fits.py record. One entry per calibration unit: the "
    "objective fingerprint (objective.py) its last completed fit answered, the capture and "
    "timbre it was fitted against, and whether the values were adopted or the shipped ones "
    "kept. status.py reads it into each voice's fit axis."
)


def load(path: Path = FITS_PATH) -> dict[str, dict]:
    if not path.exists():
        return {}
    return json.loads(path.read_text()).get("fits", {})


def save(fits: dict[str, dict], path: Path = FITS_PATH) -> None:
    body = {"_doc": DOC, "fits": {k: fits[k] for k in sorted(fits)}}
    path.write_text(json.dumps(body, indent=2) + "\n")


def unit_of(report: dict) -> str:
    """The one unit a `--program-only` report's knobs belong to."""
    units = {k["key"].partition(".")[0] for k in report.get("knobs", [])}
    if len(units) != 1:
        raise ValueError(
            f"a fit record needs knobs from exactly one patch, got {sorted(units)}; "
            f"fit with --program-only"
        )
    return units.pop()


def corpora_of(report: dict, capture: str, timbre: str) -> list[dict]:
    """The captures a fit answered, as `{capture, timbre}` in the order it was given them.

    The list is part of the fit's identity: one fitted against a patch's base
    capture alone is not the one fitted against it and its struct copy. `capture`
    and `timbre` stay beside it as the first, for readers of the single form. A
    report with no list (a fit that named no corpus, or an older one) is a list of
    the one pair the caller names.
    """
    named = [
        {"capture": c.get("capture") or "", "timbre": c.get("timbre") or ""}
        for c in report.get("corpora") or []
    ]
    if named and all(c["capture"] for c in named):
        return named
    return [{"capture": capture, "timbre": timbre}]


def entry_corpora(entry: dict) -> list[dict]:
    """The `{capture, timbre}` list a stored entry answered; readers use this, not `capture`.

    An entry that predates `corpora` is the one pair its `capture` and `timbre` name.
    """
    named = entry.get("corpora")
    if named:
        return [dict(c) for c in named]
    return [{"capture": entry.get("capture") or "", "timbre": entry.get("timbre") or ""}]


def record_fit(
    report: dict,
    *,
    capture: str,
    timbre: str,
    outcome: str,
    reason: str = "",
    bank_generation: int = 0,
    today: str | None = None,
    blocking: list[dict] | None = None,
) -> tuple[str, dict]:
    if outcome not in OUTCOMES:
        raise ValueError(f"outcome is one of {', '.join(OUTCOMES)}, not {outcome!r}")
    if (outcome == BLOCKED) != bool(blocking):
        raise ValueError("a blocked outcome, and only a blocked one, names its blocking rows")
    digest = report.get("objective")
    if not digest:
        raise ValueError("the report carries no objective fingerprint; re-run the fit")
    entry = {
        "objective": digest,
        "date": today or datetime.datetime.now(tz=datetime.UTC).date().isoformat(),
        "capture": capture,
        "timbre": timbre,
        "corpora": corpora_of(report, capture, timbre),
        "outcome": outcome,
    }
    if reason:
        entry["reason"] = reason
    if blocking:
        entry["blocking"] = blocking
    if bank_generation:
        entry["bank_generation"] = bank_generation
    base = report.get("base_overrides") or ""
    if base:
        entry["base_overrides"] = base
    if report.get("provisional_off_layer"):
        entry["provisional_off_layer"] = True
        entry["provisional_oracle"] = list(report.get("provisional_oracle") or [])
    start = report.get("start_overrides") or ""
    if start:
        entry["start_overrides"] = start
    # The terms the fit weighed, so an equivalence that added a key it weighs does not cover it.
    weights = (report.get("fit_profile") or {}).get("weights")
    if weights:
        # An explicit zero is kept: a term switched off is not a term left unset.
        entry["weights"] = dict(sorted(weights.items()))
    without = report.get("scored_without") or []
    if without:
        entry["scored_without"] = sorted(without)
    return unit_of(report), entry


def shipped_values(path: Path = BANK_VERSIONS_PATH) -> dict[str, float]:
    """Every value the tree ships, keyed `<unit>.<field>` as an override names it."""
    units = json.loads(path.read_text())["units"]
    return {
        f"{unit}.{field}": value
        for unit, body in units.items()
        for field, value in (body.get("values") or {}).items()
        if isinstance(value, (int, float))
    }


def base_is_shipped(base: str, shipped: dict[str, float]) -> bool:
    """Whether every base override names a value the tree now ships, so the fit stood on HEAD."""
    for key, value in parse_overrides(base):
        held = shipped.get(key)
        if held is None or not math.isclose(float(value), held, rel_tol=1e-6, abs_tol=1e-9):
            return False
    return True


def axis(
    units: list[str],
    fits: dict[str, dict],
    digest: str,
    equivalents: set[str] | None = None,
    shipped: dict[str, float] | None = None,
) -> dict:
    """A voice's fit state over its units: the worst of them, `none` if any has no record.

    `under_base` is a fit recorded with base overrides the tree does not ship: the constants
    it stood on are not in the tree, so it is never `current` or `equivalent`; a stale one
    stays `stale`. Base overrides every one of which equals a `shipped` value (`shipped_values`)
    are the tree's own constants, and such a fit reads as if it had none; with no `shipped`
    given, any base override reads `under_base`.
    `scored_without` is a fit scored with a term its class weighs switched off, named in
    `terms` (a search run from an oracle cache): never `current` or `equivalent` until a
    full-objective score records it again; it outranks `provisional_off_layer`.
    `provisional_off_layer` is a fit against an oracle off the slot's wanted layer, named in
    `oracle`: likewise never `current` or `equivalent`, and it outranks `under_base`.
    `equivalent` is a fit recorded under a digest proven to answer the same question as
    `digest` (`equivalence.py`); it names the recorded digests in `fitted_under`.
    `blocked` is a fit under `digest` (or an equivalent) whose trade did not settle; it
    names the gated rows in `blocking`. A later objective turns it `stale` like any record.
    """
    if not units:
        return {"state": NONE}
    entries = [fits.get(u) for u in units]

    def covered(e: dict) -> bool:
        if e.get("weights"):
            return e["objective"] in equivalence.equivalent_digests(digest, weights=e["weights"])
        pool = equivalents if equivalents is not None else equivalence.equivalent_digests(digest)
        return e["objective"] in pool

    def off_base(e: dict) -> bool:
        base = e.get("base_overrides")
        return bool(base) and (shipped is None or not base_is_shipped(base, shipped))

    if any(e is None for e in entries):
        state = NONE
    elif any(e["objective"] != digest and not covered(e) for e in entries):
        state = STALE
    elif any(e.get("scored_without") for e in entries):
        state = SCORED_WITHOUT
    elif any(e.get("provisional_off_layer") for e in entries):
        state = OFF_LAYER
    elif any(off_base(e) for e in entries):
        state = UNDER_BASE
    elif any(e.get("outcome") == BLOCKED for e in entries):
        state = BLOCKED
    elif any(e["objective"] != digest for e in entries):
        state = EQUIVALENT
    else:
        state = CURRENT
    out: dict = {"state": state}
    recorded = [e for e in entries if e is not None]
    if recorded:
        last = max(recorded, key=lambda e: e["date"])
        out.update(date=last["date"], outcome=last["outcome"])
    corpora = []
    for e in recorded:
        for c in entry_corpora(e):
            if c not in corpora:
                corpora.append(c)
    if len(corpora) > 1:
        out["corpora"] = corpora
    if state == SCORED_WITHOUT:
        out["terms"] = sorted({t for e in recorded for t in e.get("scored_without") or []})
    if state == OFF_LAYER:
        out["note"] = "provisional: fitted against an off-layer oracle"
        out["oracle"] = sorted(
            {c for e in recorded if e.get("provisional_off_layer") for c in e["provisional_oracle"]}
        )
    if state == UNDER_BASE:
        out["base_overrides"] = sorted({e["base_overrides"] for e in recorded if off_base(e)})
    if state == BLOCKED:
        out["blocking"] = [r for e in recorded for r in e.get("blocking") or []]
    if state == EQUIVALENT:
        out["fitted_under"] = sorted({e["objective"] for e in recorded if e["objective"] != digest})
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    rec = sub.add_parser("record", help="record a completed fit from its --out report")
    rec.add_argument("--report", required=True)
    rec.add_argument("--capture", required=True)
    rec.add_argument("--timbre", required=True)
    rec.add_argument("--outcome", required=True, choices=BY_HAND)
    rec.add_argument("--reason", default="")
    rec.add_argument("--bank-generation", type=int, default=0)
    sub.add_parser("digest", help="print the current objective fingerprint")
    args = ap.parse_args()
    if args.cmd == "digest":
        print(objective.objective_digest())
        return 0
    report = json.loads(Path(args.report).read_text())
    unit, entry = record_fit(
        report,
        capture=args.capture,
        timbre=args.timbre,
        outcome=args.outcome,
        reason=args.reason,
        bank_generation=args.bank_generation,
    )
    fits = load()
    fits[unit] = entry
    save(fits)
    print(f"{unit}: {entry['outcome']} under objective {entry['objective']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
