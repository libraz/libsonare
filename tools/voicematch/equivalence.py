# Comparison
# --------------------------------------------------------------------------- #


def _same(a: object, b: object) -> bool:
    """Byte-level equality of two JSON values; two NaNs are the same answer."""
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    return type(a) is type(b) and a == b


def _walk(a: object, b: object, path: str, changed: list[str], added: list[str]) -> None:
    if isinstance(a, dict) and isinstance(b, dict):
        for key in sorted(set(a) | set(b)):
            here = f"{path}.{key}"
            if key not in a:
                added.append(here)
            elif key not in b:
                changed.append(f"{here}: removed")
            else:
                _walk(a[key], b[key], here, changed, added)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            changed.append(f"{path}: {len(a)} rows -> {len(b)} rows")
        for i, (x, y) in enumerate(zip(a, b)):
            label = f"{path}[{i}]"
            if isinstance(x, dict) and "note" in x:
                label = f"{path}[timbre={x.get('timbre')!r} note={x.get('note')} velocity={x.get('velocity')}]"
            _walk(x, y, label, changed, added)
    elif not _same(a, b):
        changed.append(f"{path}: {a!r} -> {b!r}")


def compare_profiles(a: dict, b: dict) -> dict:
    """Differences between two profiles, stamps excluded, additions held apart.

    A field only `b` holds is an addition when nothing else differs; once any
    field both hold, or one only `a` holds, differs, the additions count as
    differences too.
    """
    a = {k: v for k, v in a.items() if k not in STAMP_KEYS}
    b = {k: v for k, v in b.items() if k not in STAMP_KEYS}
    changed: list[str] = []
    added: list[str] = []
    _walk(a, b, "", changed, added)
    if changed:
        return {"differences": changed + [f"{p}: added" for p in added], "additions": []}
    return {"differences": [], "additions": added}


def compare_terms(a: dict, b: dict) -> dict:
    """Case-by-case, key-by-key comparison of two terms passes.

    A key only the later tree reports is an addition, by the re-extract proof's
    rule: it passes only while every key both trees report is identical and the
    added key carries no weight in the running tree's `loss_weights` tables, so
    the loss a fit minimises cannot have moved.
    """
    diffs: list[str] = []
    added: list[str] = []
    for case in sorted(set(a) | set(b)):
        if case not in a or case not in b:
            diffs.append(f"{case}: present in only one tree")
            continue
        x, y = a[case], b[case]
        if x is None or y is None:
            if x is not y:
                diffs.append(f"{case}: {x!r} -> {y!r}")
            continue
        for key in sorted(set(x) | set(y)):
            if key not in y:
                diffs.append(f"{case}.{key}: dropped by the later tree")
            elif key not in x:
                (diffs if _weighted(key) else added).append(f"{case}.{key}")
            elif not _same(x[key], y[key]):
                diffs.append(f"{case}.{key}: {x[key]!r} -> {y[key]!r}")
    if diffs:
        diffs += [f"{k}: added" for k in added]
        added = []
    return {
        "passed": not diffs,
        "differences": diffs[:MAX_LISTED],
        "different": len(diffs),
        "additions": added[:MAX_LISTED],
        "added": len(added),
        "added_keys": sorted({k.rpartition(".")[2] for k in added}),
    }


def _weighted(key: str) -> bool:
    """Whether a terms key carries a weight in any of the objective's default profiles."""
    import loss_weights

    tables = [v for v in vars(loss_weights).values() if isinstance(v, dict)]
    return any(key in t and isinstance(t[key], int | float) for t in tables)


