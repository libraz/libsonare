def _git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(REPO), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def extract_tree(commit: str, dest: Path) -> Path:
    """`git archive <commit> tools/voicematch` (plus `tools/_repo.py`) into `dest`."""
    dest.mkdir(parents=True, exist_ok=True)
    proc = subprocess.Popen(
        ["git", "-C", str(REPO), "archive", commit, "tools/voicematch", "tools/_repo.py"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    assert proc.stdout is not None
    with tarfile.open(fileobj=proc.stdout, mode="r|") as tar:
        tar.extractall(dest, filter="data") if hasattr(tarfile, "data_filter") else tar.extractall(
            dest
        )
    err = proc.stderr.read().decode() if proc.stderr else ""
    if proc.wait() != 0:
        raise RuntimeError(f"git archive {commit} failed: {err.strip()}")
    return dest


def _env() -> dict[str, str]:
    env = dict(os.environ)
    # The shared, read-only cached corpus, whichever checkout the tree sits in.
    env.setdefault("SONARE_VOICEMATCH_ROOT", str(REPO / ".cache" / "voicematch"))
    return env


def _run_worker(mode: str, tree: Path, extra: list[str], result: Path) -> dict:
    cmd = [
        sys.executable,
        "-I",
        str(Path(__file__).resolve()),
        "_worker",
        mode,
        "--tree",
        str(tree),
        "--result",
        str(result),
        *extra,
    ]
    proc = subprocess.run(cmd, check=False, capture_output=True, text=True, env=_env())
    if proc.returncode != 0:
        raise RuntimeError(f"{mode} worker on {tree} failed:\n{proc.stderr[-2000:]}")
    return json.loads(result.read_text())


def terms_pass(tree: Path, scratch: Path, signal_set: str = "full") -> dict:
    """One tree's terms for the fixed signal set, by that tree's own code."""
    scratch.mkdir(parents=True, exist_ok=True)
    return _run_worker("terms", tree, ["--set", signal_set], scratch / "terms.json")


def prove_terms(a_tree: Path, b_tree: Path, scratch: Path, signal_set: str = "full") -> dict:
    """The terms proof over two extracted trees (each a root holding tools/voicematch)."""
    with ThreadPoolExecutor(max_workers=2) as pool:
        fa = pool.submit(terms_pass, a_tree, scratch / "a", signal_set)
        fb = pool.submit(terms_pass, b_tree, scratch / "b", signal_set)
        ra, rb = fa.result(), fb.result()
    out = compare_terms(ra["terms"], rb["terms"])
    out.update(
        signal_set=signal_set,
        cases=len(ra["terms"]),
        a_digest=ra["digest"],
        b_digest=rb["digest"],
        a_seconds=ra["seconds"],
        b_seconds=rb["seconds"],
    )
    return out


def shipped_ids(tree: Path) -> list[str]:
    cap = tree / "tools" / "voicematch" / "capture"
    return sorted(p.stem for p in cap.glob("*.json") if not p.name.endswith(".local.json"))


def _measure_chunks(tree: Path, ids: list[str], scratch: Path, jobs: int) -> list[tuple]:
    n = max(1, min(len(ids), jobs * 3))
    return [(tree, ids[i::n], scratch / f"chunk{i}.json") for i in range(n) if ids[i::n]]


def prove_reextract(a_tree: Path, b_tree: Path, scratch: Path, jobs: int = 2) -> dict:
    """The re-extraction proof over two extracted trees."""
    ids_a, ids_b = shipped_ids(a_tree), shipped_ids(b_tree)
    ids = sorted(set(ids_a) & set(ids_b))
    missing = sorted(set(ids_a) - set(ids_b))
    new_captures = sorted(set(ids_b) - set(ids_a))
    items = []
    for label, tree in (("a", a_tree), ("b", b_tree)):
        out = scratch / label
        out.mkdir(parents=True, exist_ok=True)
        for i, (t, chunk, res) in enumerate(_measure_chunks(tree, ids, out, jobs)):
            items.append((label, t, chunk, out, res.with_name(f"chunk{i}.json")))

    def run(item: tuple) -> tuple[str, dict]:
        label, tree, chunk, out, res = item
        return label, _run_worker(
            "reextract", tree, ["--ids", ",".join(chunk), "--out", str(out)], res
        )

    status: dict[str, dict[str, str]] = {"a": {}, "b": {}}
    with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        for label, got in pool.map(run, items):
            status[label].update(got["status"])

    differences: dict[str, list[str]] = {}
    additions: dict[str, list[str]] = {}
    unmeasured: dict[str, str] = {}
    identical = 0
    for cap in ids:
        sa, sb = status["a"].get(cap), status["b"].get(cap)
        if sa != "ok" or sb != "ok":
            unmeasured[cap] = f"a: {sa}, b: {sb}"
            continue
        pa = json.loads((scratch / "a" / f"{cap}.json").read_text())
        pb = json.loads((scratch / "b" / f"{cap}.json").read_text())
        cmp = compare_profiles(pa, pb)
        if cmp["differences"]:
            differences[cap] = cmp["differences"][:MAX_LISTED]
        elif cmp["additions"]:
            additions[cap] = cmp["additions"][:MAX_LISTED]
        else:
            identical += 1
    return {
        "passed": bool(ids) and not differences and not unmeasured and not missing,
        "captures": len(ids),
        "identical": identical,
        "with_additions": len(additions),
        "additions": additions,
        "differences": differences,
        "unmeasured": unmeasured,
        "removed_captures": missing,
        "new_captures": new_captures,
    }


def prove(a_commit: str, b_commit: str, *, out_dir: Path, jobs: int = 2) -> dict:
    """Run both proofs between two commits, each from its own extracted tree."""
    a_commit, b_commit = _git("rev-parse", a_commit), _git("rev-parse", b_commit)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="equiv-", dir=out_dir))
    try:
        a_tree = extract_tree(a_commit, work / "a-tree")
        b_tree = extract_tree(b_commit, work / "b-tree")
        terms = prove_terms(a_tree, b_tree, work / "terms")
        reextract = prove_reextract(a_tree, b_tree, work / "reextract", jobs)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    return {
        "a_commit": a_commit,
        "b_commit": b_commit,
        "a_digest": terms["a_digest"],
        "b_digest": terms["b_digest"],
        "reextract": reextract,
        "terms": terms,
        "passed": bool(reextract["passed"] and terms["passed"]),
    }


# --------------------------------------------------------------------------- #
# The fixed signal set (runs inside a worker, against that tree's modules)
# --------------------------------------------------------------------------- #

SAMPLE_RATE = 24_000
LEAD_S, HOLD_S, TAIL_S = 0.2, 1.0, 0.5

#: Rendering parameters of the model and the oracle side of one pitched case.
_ORACLE = {"decay": 2.5, "tilt": 1.0, "detune": 0.0, "vibrato": 0.0, "noise": 0.0, "stiffness": 0.0}
_MODEL = {"decay": 3.4, "tilt": 1.2, "detune": 7.0, "vibrato": 0.0, "noise": 0.0, "stiffness": 0.0}


def _case(name: str, note: int, velocity: int, oracle: dict, model: dict) -> dict:
    return {"name": name, "note": note, "velocity": velocity, "oracle": oracle, "model": model}


def _cases(signal_set: str) -> list[dict]:
    pitched = [_case(f"tone-n{n}-v{v}", n, v, {}, {}) for n in (48, 60, 72) for v in (40, 110)]
    extra = [
        _case("vibrato", 60, 90, {"vibrato": 30.0}, {"vibrato": 12.0}),
        _case("noisy", 64, 80, {"noise": 0.02}, {"noise": 0.005}),
        _case("inharmonic", 55, 90, {"stiffness": 4e-4}, {"stiffness": 1e-4}),
    ]
    hit = [{"name": "hit", "note": 38, "velocity": 100, "percussive": True}]
    if signal_set == "small":
        return [pitched[2]] + hit
    if signal_set == "full":
        return pitched + extra + hit
    raise ValueError(f"unknown signal set {signal_set!r}")


def _pitched(note: int, velocity: int, p: dict, seed: int):
    import numpy as np

    n = int((LEAD_S + HOLD_S + TAIL_S) * SAMPLE_RATE)
    t = np.arange(n) / SAMPLE_RATE - LEAD_S
    on = t >= 0.0
    tt = np.where(on, t, 0.0)
    f0 = 440.0 * 2.0 ** ((note - 69) / 12.0) * 2.0 ** (p["detune"] / 1200.0)
    f = f0 * (1.0 + (2.0 ** (p["vibrato"] / 1200.0) - 1.0) * np.sin(2 * np.pi * 5.5 * tt))
    phase = 2 * np.pi * np.cumsum(f) / SAMPLE_RATE
    tilt = p["tilt"] - 0.6 * velocity / 127.0
    out = np.zeros(n)
    for k in range(1, 13):
        ratio = k * math.sqrt(1.0 + p["stiffness"] * k * k)
        if f0 * ratio > 0.45 * SAMPLE_RATE:
            break
        amp = k ** (-tilt) * np.exp(-tt * p["decay"] * (1.0 + 0.15 * k))
        out += amp * np.sin(ratio * phase)
    out *= velocity / 127.0 * np.minimum(tt / 0.005, 1.0) * on
    if p["noise"]:
        rng = np.random.default_rng(seed)
        out += p["noise"] * rng.standard_normal(n) * np.exp(-tt * p["decay"] * 0.5) * on
    return out


def _hit(modes: tuple, decay: float, seed: int):
    import numpy as np

    n = int((LEAD_S + HOLD_S + TAIL_S) * SAMPLE_RATE)
    t = np.arange(n) / SAMPLE_RATE - LEAD_S
    on = t >= 0.0
    tt = np.where(on, t, 0.0)
    rng = np.random.default_rng(seed)
    out = 0.3 * rng.standard_normal(n) * np.exp(-tt * 40.0)
    for i, hz in enumerate(modes):
        out += (0.6 / (i + 1)) * np.sin(2 * np.pi * hz * tt) * np.exp(-tt * decay * (1 + i))
    return out * on


def _terms_for(case: dict, loss, patterns, Note, np) -> dict | None:
    note = Note(case["note"], case["velocity"], LEAD_S, HOLD_S)
    percussive = bool(case.get("percussive"))
    pattern = patterns.Pattern(
        name=case["name"], notes=[note], analysis_notes=[note], tail=TAIL_S, percussive=percussive
    )
    if percussive:
        signals = (
            _hit((190.0, 340.0, 560.0), 6.0, 5),
            _hit((180.0, 330.0, 540.0), 8.0, 5),
        )
    else:
        model = {**_MODEL, **case["model"]}
        oracle = {**_ORACLE, **case["oracle"]}
        signals = (
            _pitched(case["note"], case["velocity"], model, 11),
            _pitched(case["note"], case["velocity"], oracle, 13),
        )

    def rows(raw, masks=None):
        mono = raw / (float(np.sqrt(np.mean(raw**2))) / 0.1)
        return loss.probe_rows(mono, pattern, SAMPLE_RATE, raw=raw, tnr_masks=masks)

    oracle_rows = rows(signals[1])
    masks = None if percussive else loss.oracle_tnr_masks(oracle_rows)
    model_rows = rows(signals[0], masks)
    return loss.score_terms(model_rows, oracle_rows, mss=0.0, percussive=percussive)


def _enter(tree: Path) -> None:
    """Make `tree`'s tools/voicematch the only place its modules come from."""
    here = str(HERE)
    sys.path[:] = [p for p in sys.path if p not in ("", here)]
    sys.path[:0] = [str(tree / "tools" / "voicematch"), str(tree / "tools")]


def _worker_terms(tree: Path, signal_set: str) -> dict:
    _enter(tree)
    import loss
    import numpy as np
    import objective
    import patterns
    from smf import Note

    start = time.perf_counter()
    terms = {c["name"]: _terms_for(c, loss, patterns, Note, np) for c in _cases(signal_set)}
    return {
        "digest": objective.objective_digest(),
        "terms": terms,
        "seconds": round(time.perf_counter() - start, 2),
    }


def _worker_reextract(tree: Path, ids: list[str], out: Path) -> dict:
    import contextlib
    import io

    _enter(tree)
    import profile as profile_module

    from capture import load_config, out_root

    status = {}
    for cap_id in ids:
        try:
            cfg = load_config(tree / "tools" / "voicematch" / "capture" / f"{cap_id}.json")
            corpus = out_root(cfg, "")
            if not (corpus / "manifest.json").exists():
                status[cap_id] = "no-cache"
                continue
            with (
                contextlib.redirect_stdout(io.StringIO()),
                contextlib.redirect_stderr(io.StringIO()),
            ):
                rc = profile_module.measure(cfg, corpus, out / f"{cap_id}.json")
            status[cap_id] = "ok" if rc == 0 else f"measure-failed:{rc}"
        except Exception as exc:  # noqa: BLE001 - one capture's failure must not hide the rest
            status[cap_id] = f"error:{type(exc).__name__}:{exc}"
    return {"status": status}


