def _summary(result: dict) -> str:
    r, t = result["reextract"], result["terms"]
    verdict = {True: "PASS", False: "FAIL"}
    head = f"{result['a_commit'][:10]} ({result['a_digest']}) vs "
    head += f"{result['b_commit'][:10]} ({result['b_digest']})"
    re_line = (
        f"  re-extract: {verdict[r['passed']]} -- {r['identical']}/{r['captures']} identical, "
    )
    re_line += f"{r['with_additions']} with additions only, {len(r['differences'])} differing, "
    re_line += f"{len(r['unmeasured'])} unmeasured"
    terms_line = f"  terms:      {verdict[t['passed']]} -- {t['cases']} cases, "
    terms_line += (
        f"{t['different']} differing value(s), {t.get('added', 0)} unweighted key(s) added "
        f"({t['a_seconds']} s / {t['b_seconds']} s per tree)"
    )
    lines = [head, re_line, terms_line]
    for cap, diffs in list(r["differences"].items())[:5]:
        lines += [f"    {cap}: {d}" for d in diffs[:3]]
    for cap, why in list(r["unmeasured"].items())[:5]:
        lines.append(f"    {cap}: unmeasured ({why})")
    lines += [f"    {d}" for d in t["differences"][:5]]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prove", help="run both proofs between two commits")
    p.add_argument("a")
    p.add_argument("b")
    p.add_argument("--out", default=str(REPO / ".cache" / "voicematch" / "equivalence"))
    p.add_argument("--jobs", type=int, default=2)
    p.add_argument("--record", action="store_true", help="append the pair when both proofs pass")
    sub.add_parser("list", help="print the recorded equivalences")
    w = sub.add_parser("_worker")
    w.add_argument("mode", choices=("terms", "reextract"))
    w.add_argument("--tree", required=True)
    w.add_argument("--result", required=True)
    w.add_argument("--set", default="full")
    w.add_argument("--ids", default="")
    w.add_argument("--out", default="")
    args = ap.parse_args(argv)

    if args.cmd == "_worker":
        tree = Path(args.tree)
        if args.mode == "terms":
            got = _worker_terms(tree, args.set)
        else:
            got = _worker_reextract(tree, [i for i in args.ids.split(",") if i], Path(args.out))
        Path(args.result).write_text(json.dumps(got))
        return 0
    if args.cmd == "list":
        for e in load():
            print(
                f"{e['a']} <-> {e['b']}  {e['a_commit'][:10]}..{e['b_commit'][:10]}  {e['proved_utc']}"
            )
        return 0
    result = prove(args.a, args.b, out_dir=Path(args.out), jobs=args.jobs)
    print(_summary(result))
    if not result["passed"]:
        return 1
    if args.record:
        entry = record(result)
        print(f"recorded {entry['a']} <-> {entry['b']} in {EQUIVALENCES_PATH.name}")
    return 0


