"""Objective fingerprints proven to answer the same question.

`objective.objective_digest()` hashes code text, so it cannot tell a refactor
from a change of question: any code edit marks every fit stale. This module
records the pairs of digests for which that was shown not to matter, in
`objective-equivalences.json`, so `fits.axis` can call a fit `equivalent`
instead of `stale`. The digest itself is not weakened.

Two commits are proven equivalent by running each tree's own code, extracted
with `git archive` into a scratch directory, over two checks that both have to
pass:
  - re-extraction: `profile.measure` over every shipped capture's cached
    corpus gives the same profile in both trees, stamps aside. A field only
    the later tree holds is an addition, reported apart: it changes no
    quantity the earlier tree measured, provided everything both hold is
    byte-identical;
  - terms: a fixed set of synthetic model/oracle pairs, measured by the
    tree's `loss.probe_rows` and reduced by `loss.score_terms`, gives the same
    terms dict, key for key and value for value.

    uv run --locked --project bindings/python python \\
        tools/voicematch/equivalence.py prove <commit-a> <commit-b> [--record]
"""

from __future__ import annotations

import argparse
import datetime
import json
import math
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
EQUIVALENCES_PATH = HERE / "objective-equivalences.json"

#: Profile keys that date a measurement rather than measure anything.
STAMP_KEYS = ("measured_utc", "field_measured_utc")

#: How many field paths one evidence list keeps.
MAX_LISTED = 20

DOC = (
    "Generated by tools/voicematch/equivalence.py prove --record. Pairs of objective "
    "fingerprints (objective.py) shown to answer the same question: the two commits, run "
    "from their own code, re-extract every shipped capture to the same profile and give "
    "identical loss terms on a fixed signal set. fits.json entries recorded under either "
    "digest read as `equivalent` to the other in the fit axis instead of `stale`. The "
    "relation is symmetric and transitive; a pair is only ever added by a passing proof."
)


# --------------------------------------------------------------------------- #
# The record
# --------------------------------------------------------------------------- #


def load(path: Path = EQUIVALENCES_PATH) -> list[dict]:
    if not path.exists():
        return []
    return json.loads(path.read_text()).get("equivalences", [])


def save(entries: list[dict], path: Path = EQUIVALENCES_PATH) -> None:
    path.write_text(json.dumps({"_": DOC, "equivalences": entries}, indent=2) + "\n")


def equivalent_digests(
    digest: str, path: Path = EQUIVALENCES_PATH, weights: dict[str, float] | None = None
) -> set[str]:
    """Every other digest reachable from `digest` through recorded pairs.

    A pair whose later tree added a terms key holds only for a fit that put no
    weight on that key: given the fit's own @p weights, such a pair is not walked.
    """
    edges: dict[str, set[str]] = {}
    for e in load(path):
        if weights and any(weights.get(k, 0.0) > 0.0 for k in e.get("added_keys", ())):
            continue
        edges.setdefault(e["a"], set()).add(e["b"])
        edges.setdefault(e["b"], set()).add(e["a"])
    seen = {digest}
    pending = [digest]
    while pending:
        for nxt in edges.get(pending.pop(), ()):
            if nxt not in seen:
                seen.add(nxt)
                pending.append(nxt)
    return seen - {digest}


def record(result: dict, path: Path = EQUIVALENCES_PATH) -> dict:
    """Append the proven pair; raises unless both proofs passed and the digests differ."""
    for name in ("reextract", "terms"):
        if not (result.get(name) or {}).get("passed"):
            raise ValueError(f"the {name} proof did not pass; nothing to record")
    if result["a_digest"] == result["b_digest"]:
        raise ValueError(f"both commits carry digest {result['a_digest']}; nothing to record")
    entry = {
        "a": result["a_digest"],
        "b": result["b_digest"],
        "a_commit": result["a_commit"],
        "b_commit": result["b_commit"],
        "proved_utc": datetime.datetime.now(tz=datetime.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        # Terms keys only the later tree reports: a fit weighing one is not covered.
        "added_keys": sorted(result["terms"].get("added_keys") or []),
        "evidence": {
            "reextract": {k: v for k, v in result["reextract"].items() if k != "passed"},
            "terms": {k: v for k, v in result["terms"].items() if k != "passed"},
        },
    }
    pair = {entry["a"], entry["b"]}
    entries = [e for e in load(path) if {e["a"], e["b"]} != pair]
    entries.append(entry)
    save(entries, path)
    return entry


