/**
 * @file Writes `src/sonare-analysis.js.d.ts` from the analysis-only module's registrations.
 *
 * The analysis-only build registers a subset of the full module's embind
 * functions, so its factory resolves to `Pick<SonareModule, ...>` over exactly
 * the names the built `dist/sonare-analysis.js` carries. The list is read off an
 * instantiated module rather than the C++ sources, because which registrations
 * survive is decided by the preprocessor gates and the analysis source set.
 * Runs first in `build:js`, so a binary built here or copied in is declared by the
 * normal build; with no analysis binary in `dist/` it leaves the file alone.
 * `tests/analysis-entry.test.ts` fails when the two part.
 */

import { access, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

/** Emscripten runtime methods the module exports beside its embind registrations. */
export const RUNTIME_METHODS = new Set(['UTF8ToString']);

const PACKAGE_ROOT = new URL('../', import.meta.url);
const TARGET = new URL('src/sonare-analysis.js.d.ts', PACKAGE_ROOT);

/** The embind names the built analysis module registers, sorted. */
export async function analysisRegistrations(root = PACKAGE_ROOT) {
  const createModule = (await import(new URL('dist/sonare-analysis.js', root).href)).default;
  return Object.keys(await createModule())
    .filter((name) => !RUNTIME_METHODS.has(name))
    .sort();
}

/** The declaration text for @p names. */
export function declarationText(names) {
  return `// Generated by scripts/write-analysis-module-types.mjs from the built module; do not edit.
import type { SonareModule } from './sonare.js';

/** The part of {@link SonareModule} the analysis-only build registers. */
export type SonareAnalysisModule = Pick<
  SonareModule,
${names.map((name) => `  | '${name}'`).join('\n')}
>;

declare const createSonareAnalysis: (options?: {
  locateFile?: (path: string, prefix: string) => string;
  wasmBinary?: ArrayBuffer | Uint8Array;
}) => Promise<SonareAnalysisModule>;

export default createSonareAnalysis;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const binary = new URL('dist/sonare-analysis.js', PACKAGE_ROOT);
  const present = await access(binary).then(
    () => true,
    () => false,
  );
  if (!present) {
    console.log(`no ${fileURLToPath(binary)}; analysis module declaration left as is`);
    process.exit(0);
  }
  const names = await analysisRegistrations();
  await writeFile(TARGET, declarationText(names));
  console.log(`wrote ${fileURLToPath(TARGET)} (${names.length} registrations)`);
}
